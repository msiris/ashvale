/**
 * 말투 덧입힘 — 가까워진 뒤의 어휘 (§15.1).
 *
 * **`companion-dialogue.ts` 를 고치지 않는다.** 그 파일은 수정 금지다.
 * 대신 friend·lover 단계의 호칭과 교류 대사만 여기서 덮어쓴다.
 * 낮은 단계(stranger·ally)는 원본 그대로 둔다 — 처음부터 살갑게 굴면
 * 가까워지는 과정이 사라진다. **멀다가 가까워지는 낙차가 이 게임의 관계다.**
 *
 * 톤: 오빠를 부르는 여동생. 존댓말을 벗은 뒤의 반말이되,
 * 툭툭 던지는 반말이 아니라 **기대고 조르고 삐치는** 반말이다.
 *   - 호칭은 '오빠' 로 고정한다
 *   - 어미: `-잖아` `-란 말이야` `-거든` `-지 마` `-줘` `-야?`
 *   - 외형 묘사 금지(§15.1). 행동·말투·태도로만 드러낸다
 *
 * 되돌리려면 이 파일의 `SIBLING_VOICE` 를 비우면 된다. 원본으로 돌아간다.
 */

import type { AffinityTier } from './companion-dialogue';

export interface VoiceOverlay {
  /** 주인공을 부르는 말 */
  address?: Partial<Record<AffinityTier, string>>;
  /** 교류 대사. 단계별로 **갈아 끼운다** */
  talk?: Partial<Record<AffinityTier, string[]>>;
  /**
   * 원본 뒤에 **덧붙일** 대사.
   *
   * 낯선 사람·아는 사이 단계는 원본 톤이 그대로 좋으므로 갈아 끼우지 않는다.
   * 대신 같은 결로 몇 줄을 더해 같은 말만 반복되지 않게 한다.
   */
  extra?: Partial<Record<AffinityTier, string[]>>;
}

