/**
 * 교류 대사 덧줄 (§15.1).
 *
 * **`companion-dialogue.ts` 를 고치지 않는다.** 그 파일은 수정 금지다.
 * 원본은 단계마다 3줄뿐이라 몇 주 놀면 같은 말이 돌아온다.
 * 여기에 **덧붙일 줄만** 둔다.
 *
 * 원래 이 파일은 가까워진 뒤 호칭을 '오빠' 로 바꾸는 덧입힘이었다.
 * 그런데 나들이·부탁·연애 사건은 호감 단계를 따로 보지 않아서,
 * **처음 본 사람이 오빠라고 부르는 자리가 생겼다.** 낙차를 만들려고 넣은 것이
 * 반대로 낙차를 없앤 셈이다. 호칭은 원본(`address`)으로 되돌리고,
 * 여기는 줄만 늘린다.
 *
 * 문체는 원본 결을 따라간다.
 *   - `stranger` `ally`: 존댓말. 아직 거리가 있다
 *   - `friend` `lover`: 반말. 다만 호칭은 원본이 정한 것을 쓴다
 *   - 외형 묘사 금지(§15.1). 행동·말투·태도로만 드러낸다
 *
 * 되돌리려면 이 파일의 `EXTRA_VOICE` 를 비우면 된다. 원본 3줄로 돌아간다.
 */

