/**
 * 주간 부탁 (§7.3, §11).
 *
 * **새로 쓴 파일이다.**
 *
 * 매주 하는 일이 똑같았다 — 제일 좋은 지역에 제일 좋은 동행과 나가고,
 * 자원 되는 대로 건물을 올린다. 답이 하나뿐이라 고민이 없다.
 *
 * 부탁은 그 주의 답을 흔든다. 한 주에 한 번만 나갈 수 있으므로(§3)
 * **둘이 다른 지역을 부탁하면 하나만 들어줄 수 있다.** 들어준 쪽은 호감이
 * 오르고, 못 들어준 쪽은 조금 서운해한다. 벌이 아니라 기회비용이다.
 *
 * 문체는 §15.1. 부탁은 호감 40 이상에서만 오므로 반말이다.
 * 토큰: {지역} 부탁한 지역 이름, {거점} 마을 이름.
 */

export interface RequestLine {
  /** 부탁하는 말 */
  ask: string;
  /** 들어줬을 때 */
  done: string;
  /** 그 주가 지나도록 안 갔을 때. 원망하지 않는다 */
  missed: string;
}

