/**
 * 동화 에피소드 (§11 곁가지).
 *
 * **지역 탐사와 다른 자리다.** 지역은 판정과 전리품이고, 여기는 이야기다.
 * 지역 탐사를 그대로 두고 옆에 붙인다 — 나가는 곳이 하나뿐이라 매주 같은
 * 표식을 같은 주사위로 캐는 일만 남아 있었다.
 *
 * 여기서 **동료가 들어온다.** 원래 인물은 의뢰인의 소개나 맹우의 소개
 * 연쇄로만 들어왔는데(§7.4), 그 길은 조건이 까다로워 오래 놀아도 명단이
 * 세 명에서 멈추곤 했다. 에피소드는 눈에 보이는 세 번째 길이다.
 *
 * 규칙:
 *   - 장(beat) 셋. 장마다 선택지 셋. 선택마다 결(favor) 0~2
 *   - 합이 EPISODE_FAVOR_PASS 이상이면 그 사람이 따라온다
 *   - 모자라면 **끝나지 않는다.** 지운 표를 남기지 않으니 다시 갈 수 있다
 *
 * 문체는 §15 를 따른다.
 *   - 서술은 무주어 문어체 과거형. 2인칭을 쓰지 않는다
 *   - 선택지는 지금 하는 행동을 적는다. 따옴표 안은 말한 그대로
 *
 * 토큰: {거점} 마을 이름.
 */

import type { FactionId, ResourceId } from '@/types/game';

/** 이 결 이상이면 동료가 따라온다. 최대 6 */
export const EPISODE_FAVOR_PASS = 3;

export interface EpisodeChoice {
  text: string;
  /** 고른 뒤 남는 한 줄. 무주어 문어체 과거형 */
  result: string;
  /** 그 사람의 마음이 기우는 정도. 0~2 */
  favor: number;
  xp?: number;
  hp?: number;
  resources?: Partial<Record<ResourceId, number>>;
  faction?: { id: FactionId; delta: number };
}

export interface EpisodeBeat {
  id: string;
  text: string;
  choices: EpisodeChoice[];
}

export interface Episode {
  id: string;
  title: string;
  /** 데려오려는 원형. 이미 있으면 빈 원형이 대신 온다 */
  archetypeId: string;
  /** 이 에피소드를 끝내야 열린다 */
  needs?: string;
  /** 이 주차부터 열린다. HUD 에 보이는 주차와 같은 수다 (1부터) */
  fromTurn: number;
  /** 목록에 적히는 한 줄 */
  lure: string;
  /** 들어설 때 */
  intro: string;
  beats: EpisodeBeat[];
  /** 결이 찼을 때 — 따라온다 */
  join: string;
  /** 모자랐을 때 */
  miss: string;
}

