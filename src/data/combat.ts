/**
 * 마주섬 수치 (§11) — 체력을 두고 겨룬다.
 *
 * 처음에는 기세 저울(−2..+2) 세 판이었다. 세 번 고르면 끝이라 **맞부딪히는
 * 무게가 없었다.** 이제 양쪽이 체력을 들고 서고, 한쪽이 다할 때까지 간다.
 *
 * 규칙은 그대로 **읽고 고르는 것**이다. 때리는 버튼을 연타하는 자리가 아니다.
 *   기색을 읽고 자세로 맞선다 → **방향**이 정해진다 (누가 깎이는가)
 *   겹치는 순간에 누른다 → **크기**가 정해진다 (얼마나 깎이는가)
 * 손이 결과를 뒤집지는 않는다. 잘못 읽으면 맞고, 손이 좋으면 덜 맞을 뿐이다.
 *
 * 수치는 네댓 번에서 예닐곱 번 사이에 갈리도록 잡았다. 너무 짧으면
 * 읽을 기회가 없고, 너무 길면 같은 화면을 계속 누르는 일이 된다.
 */

/** 내 체력의 바탕. 여기에 기력 상한의 일부가 더해진다 */
export const PLAYER_HP_BASE = 20;
/** 기력 상한을 이만큼 나눠 체력에 더한다 — 자라면 더 버틴다 */
export const PLAYER_HP_PER_VIGOR = 3;
/** 결(favor)이 체력으로 붙는 비율. 오는 길을 잘 걸었으면 더 버틴다 */
export const FAVOR_TO_HP = 0.5;

/** 상대 체력의 바탕. 난도가 그대로 더해진다 */
export const FOE_HP_BASE = 8;

/** 이겼을 때 상대를 깎는 바탕 */
export const HIT_BASE = 4;
/** 능력치를 이만큼 나눠 피해에 더한다 */
export const HIT_PER_STAT = 6;
/** 때를 잡았을 때 더 깎는 양 */
export const HIT_TIMED_BONUS = 2;

/**
 * 졌을 때 내가 깎이는 바탕. 난도가 일부 더해진다.
 *
 * **이기는 쪽과 비슷해야 한다.** 맞는 쪽이 더 작으면 아무 자세나 반복해도
 * 한 번 이기고 한 번 지는 것이 이득이 되어, 읽는 일이 값을 잃는다.
 */
export const FOE_HIT_BASE = 3;
export const FOE_HIT_PER_DIFFICULTY = 7;
/** 맞는 순간에 때를 잡으면 이만큼 줄어든다 (반올림 올림) */
export const GUARD_RATIO = 0.5;

/** 서로 같은 자세였을 때. 둘 다 조금 깎인다 — 팽팽해도 시간이 간다 */
export const CLASH_CHIP = 1;

/**
 * 이 판 수를 넘기면 그 자리에서 끝낸다.
 *
 * 서로 못 깎는 상황이 이어지면 같은 화면을 계속 누르게 된다.
 * 넘기면 **체력이 많은 쪽이 이긴 것으로 본다.**
 */
export const MAX_ROUNDS = 12;
